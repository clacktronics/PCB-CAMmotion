#!/usr/bin/env node
// Bundles the app into dist/app.js, a classic script: browsers refuse ES modules loaded from
// file://, and the app must work opened straight from disk (AGENTS.md → Static app).
// The bundle is committed so a fresh clone runs without any build.
//
//   node tools/build.mjs          rebuild dist/app.js
//   node tools/build.mjs --check  fail if dist/app.js is out of date (part of npm run lint)

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = join(root, 'dist/app.js');

const result = await build({
  entryPoints: [join(root, 'src/ui/main.js')],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'inline',
  write: false,
  outfile,
  absWorkingDir: root,
  banner: { js: '// Generated by tools/build.mjs from src/ — do not edit. Run `npm run build`.' },
});
const code = result.outputFiles[0].text;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outfile, 'utf8');
  } catch {}
  if (current !== code) {
    console.error('dist/app.js is out of date: run `npm run build` and commit it');
    process.exit(1);
  }
  console.log('dist/app.js is up to date');
} else {
  mkdirSync(dirname(outfile), { recursive: true });
  writeFileSync(outfile, code);
  console.log(`wrote dist/app.js (${(code.length / 1024).toFixed(1)} KB)`);
}
