#!/usr/bin/env node
// Bundle src/ui/main.js into dist/app.js (a classic script, so index.html also works when opened
// straight from disk: browsers block ES module imports on file://).
//
//   node tools/build.mjs          write dist/app.js
//   node tools/build.mjs --check  fail if dist/app.js is out of date (used by npm run lint)

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist/app.js');
const res = await build({
  entryPoints: [join(root, 'src/ui/main.js')],
  bundle: true,
  format: 'iife',
  target: ['es2022'],
  write: false,
  legalComments: 'inline',
  banner: { js: '// PCB-CAMmotion — generated by tools/build.mjs from src/. Do not edit; run `npm run build`.' },
  logLevel: 'warning',
});
const code = res.outputFiles[0].text;
if (process.argv.includes('--check')) {
  let old = '';
  try {
    old = readFileSync(out, 'utf8');
  } catch {}
  if (old !== code) {
    console.error('dist/app.js is out of date: run `npm run build` and commit it');
    process.exit(1);
  }
  console.log('dist/app.js is up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, code);
  console.log(`wrote dist/app.js (${(code.length / 1024).toFixed(0)} KB)`);
}
